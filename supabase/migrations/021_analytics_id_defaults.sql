-- Align analytics identity columns with the baseline schema and ensure their
-- sequences start above existing IDs imported before the identities were used.
LOCK TABLE public.analytics_events, public.analytics_persons,
  public.analytics_flags, public.analytics_sessions
  IN SHARE ROW EXCLUSIVE MODE;

ALTER TABLE public.analytics_events
  ALTER COLUMN id SET NOT NULL,
  ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE public.analytics_persons
  ALTER COLUMN id SET NOT NULL,
  ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE public.analytics_flags
  ALTER COLUMN id SET NOT NULL,
  ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE public.analytics_sessions
  ALTER COLUMN id SET NOT NULL,
  ALTER COLUMN id SET GENERATED BY DEFAULT;

SELECT setval('public.analytics_events_id_seq'::regclass,
  GREATEST(COALESCE((SELECT max(id) FROM public.analytics_events), 0),
           COALESCE((SELECT last_value FROM pg_sequences
                     WHERE schemaname = 'public'
                       AND sequencename = 'analytics_events_id_seq'), 0)) + 1,
  false);
SELECT setval('public.analytics_persons_id_seq'::regclass,
  GREATEST(COALESCE((SELECT max(id) FROM public.analytics_persons), 0),
           COALESCE((SELECT last_value FROM pg_sequences
                     WHERE schemaname = 'public'
                       AND sequencename = 'analytics_persons_id_seq'), 0)) + 1,
  false);
SELECT setval('public.analytics_flags_id_seq'::regclass,
  GREATEST(COALESCE((SELECT max(id) FROM public.analytics_flags), 0),
           COALESCE((SELECT last_value FROM pg_sequences
                     WHERE schemaname = 'public'
                       AND sequencename = 'analytics_flags_id_seq'), 0)) + 1,
  false);
SELECT setval('public.analytics_sessions_id_seq'::regclass,
  GREATEST(COALESCE((SELECT max(id) FROM public.analytics_sessions), 0),
           COALESCE((SELECT last_value FROM pg_sequences
                     WHERE schemaname = 'public'
                       AND sequencename = 'analytics_sessions_id_seq'), 0)) + 1,
  false);

GRANT USAGE, SELECT ON SEQUENCE public.analytics_events_id_seq,
  public.analytics_persons_id_seq, public.analytics_flags_id_seq,
  public.analytics_sessions_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
